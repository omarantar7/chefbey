import {
  readdirSync,
  writeFileSync,
  existsSync,
  unlinkSync,
  mkdirSync,
} from "fs";
import { join } from "path";
import { drizzle } from "drizzle-orm/libsql";
import { content } from "../lib/db/schema/content";
import { contentLocal } from "../lib/db/schema/contentLocal";
import { eq, and } from "drizzle-orm";
import env from "../lib/env";

const db = drizzle(env.TURSO_DATABASE_URL, { casing: "snake_case" });
const languages = env.CONTENT_LANGUAGES;

const EXCLUDED_FILES = ["index.ts", "types.ts", "field-types.ts"];

function getFiles(dir: string) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter(
    (f) => f.endsWith(".ts") && !EXCLUDED_FILES.includes(f),
  );
}

async function generateRegistry(
  dir: string,
  files: string[],
  outputPath: string,
  registryName: string,
) {
  const registry: Record<string, any> = {};

  for (const file of files) {
    const module = await import(join(dir, file) + `?t=${Date.now()}`);
    const definition = module.default;
    if (!definition) continue;
    registry[definition.type] = definition;
  }

  if (existsSync(outputPath)) {
    unlinkSync(outputPath);
    console.log(`🗑 Deleted old ${outputPath}`);
  }

  const output = `// Auto-generated by sync-content-types script. Do not edit manually.
import type { ContentTypeDefinition, ContentsTypeDefinition } from "@/config/index";

const ${registryName}: Record<string, any> = ${JSON.stringify(registry, null, 2)};

export default ${registryName};
`;

  writeFileSync(outputPath, output, "utf-8");
  console.log(`📄 Generated ${outputPath}`);
}

async function seedDir(dir: string, files: string[]) {
  for (const file of files) {
    const module = await import(join(dir, file) + `?t=${Date.now()}`);
    const definition = module.default;

    if (!definition) {
      console.warn(`⚠ Skipping "${file}" — no default export found.`);
      continue;
    }

    const { name, type } = definition;

    const [existingContent] = await db
      .select()
      .from(content)
      .where(eq(content.type, type))
      .limit(1);

    let contentRow = existingContent;

    if (contentRow) {
      console.log(`⏭ Skipping "${name}" (type: "${type}") — already exists.`);
    } else {
      const [inserted] = await db
        .insert(content)
        .values({ name, type, attrs: null })
        .returning();

      contentRow = inserted;
      console.log(`✅ Inserted "${name}" (type: "${type}")`);
    }

    for (const language of languages) {
      const [existingLocale] = await db
        .select()
        .from(contentLocal)
        .where(
          and(
            eq(contentLocal.contentId, contentRow.id),
            eq(contentLocal.language, language),
          ),
        )
        .limit(1);

      if (existingLocale) {
        console.log(
          `  ⏭ Skipping locale "${language}" for "${name}" — already exists.`,
        );
        continue;
      }

      await db.insert(contentLocal).values({
        contentId: contentRow.id,
        language,
        title: name,
        attrs: null,
      });

      console.log(`  ✅ Inserted locale "${language}" for "${name}"`);
    }
  }
}

function generateRouteFiles(files: string[]) {
  for (const file of files) {
    const typeName = file.replace(".ts", "");
    const dir = join(process.cwd(), `app/pages/admin/contents/${typeName}`);

    if (!existsSync(dir)) {
      mkdirSync(dir, { recursive: true });
      console.log(`📁 Created directory ${dir}`);
    }

    // [id].vue
    const idFilePath = join(dir, "[id].vue");

    if (existsSync(idFilePath)) {
      console.log(`⏭ Skipping [id].vue for "${typeName}" — already exists.`);
    } else {
      const idContent = `<script setup lang="ts">
import contentsTypeRegistry from "~~/config/contents-type-registry";

definePageMeta({ layout: "admin", props: true });

type Props = { id: string };
const { id } = defineProps<Props>();

const route = useRoute();
const typeName = route.params.type as string;
const definition = computed(() => contentsTypeRegistry[\`contents:\${typeName}\`]?.fields);
</script>

<template>
  <div class="p-8">
    <pre>{{ definition }}</pre>
    <pre>id: {{ id }}</pre>
  </div>
</template>
`;
      writeFileSync(idFilePath, idContent, "utf-8");
      console.log(
        `✅ Created route file pages/admin/contents/${typeName}/[id].vue`,
      );
    }

    // index.vue
    const indexFilePath = join(dir, "index.vue");

    if (existsSync(indexFilePath)) {
      console.log(`⏭ Skipping index.vue for "${typeName}" — already exists.`);
    } else {
      const indexContent = `<script setup lang="ts">

definePageMeta({ layout: "admin" });
</script>

<template>
  <div class="p-8">
    <div class="mb-6 flex items-center justify-between">
      <h1>${typeName}</h1>
      <UButton
        label="Add New"
        color="primary"
        icon="i-heroicons-plus"
      />
    </div>
  </div>
</template>
`;
      writeFileSync(indexFilePath, indexContent, "utf-8");
      console.log(
        `✅ Created route file pages/admin/contents/${typeName}/index.vue`,
      );
    }

    // API files
    const apiDir = join(process.cwd(), `server/api/contents/${typeName}`);

    if (!existsSync(apiDir)) {
      mkdirSync(apiDir, { recursive: true });
      console.log(`📁 Created API directory ${apiDir}`);
    }

    // server/api/contents/[typeName]/index.ts
    const apiIndexPath = join(apiDir, "index.ts");

    if (existsSync(apiIndexPath)) {
      console.log(`⏭ Skipping index.ts for "${typeName}" — already exists.`);
    } else {
      const apiIndexContent = `export default defineEventHandler(async (event) => {
  if (event.method === "GET") {
    // TODO: return all ${typeName}
    return [];
  }

  if (event.method === "POST") {
    const body = await readBody(event);
    // TODO: insert new ${typeName}
    return { success: true };
  }

  throw createError({ status: 405, message: "Method not allowed" });
});
`;
      writeFileSync(apiIndexPath, apiIndexContent, "utf-8");
      console.log(
        `✅ Created API file server/api/contents/${typeName}/index.ts`,
      );
    }

    // server/api/contents/[typeName]/[id].ts
    const apiIdPath = join(apiDir, "[id].ts");

    if (existsSync(apiIdPath)) {
      console.log(`⏭ Skipping [id].ts for "${typeName}" — already exists.`);
    } else {
      const apiIdContent = `export default defineEventHandler(async (event) => {
  const id = getRouterParam(event, "id");

  if (event.method === "GET") {
    // TODO: return ${typeName} by id
    return { id };
  }

  if (event.method === "PUT") {
    const body = await readBody(event);
    // TODO: update ${typeName} by id
    return { success: true };
  }

  if (event.method === "DELETE") {
    // TODO: delete ${typeName} by id
    return { success: true };
  }

  throw createError({ status: 405, message: "Method not allowed" });
});
`;
      writeFileSync(apiIdPath, apiIdContent, "utf-8");
      console.log(
        `✅ Created API file server/api/contents/${typeName}/[id].ts`,
      );
    }
  }
}

async function seedContentTypes() {
  const contentTypesDir = join(process.cwd(), "config/content-types");
  const contentsDir = join(process.cwd(), "config/contents");

  const contentTypeFiles = getFiles(contentTypesDir);
  const contentsFiles = getFiles(contentsDir);

  console.log(`Found ${contentTypeFiles.length} content type(s)...`);
  console.log(`Found ${contentsFiles.length} content(s)...`);
  console.log(`Languages: ${languages.join(", ")}`);

  // Seed content-types
  console.log("\n--- Seeding content-types ---");
  await seedDir(contentTypesDir, contentTypeFiles);

  // Seed contents
  console.log("\n--- Seeding contents ---");
  await seedDir(contentsDir, contentsFiles);

  // Generate content-type-registry.ts
  await generateRegistry(
    contentTypesDir,
    contentTypeFiles,
    join(process.cwd(), "config/content-type-registry.ts"),
    "contentTypeRegistry",
  );

  // Generate contents-type-registry.ts
  await generateRegistry(
    contentsDir,
    contentsFiles,
    join(process.cwd(), "config/contents-type-registry.ts"),
    "contentsTypeRegistry",
  );
  // Generate route files for contents
  console.log("\n--- Generating route files ---");
  generateRouteFiles(contentsFiles);

  console.log("\nDone.");
  process.exit(0);
}

seedContentTypes().catch((err) => {
  console.error("Error:", err);
  process.exit(1);
});
